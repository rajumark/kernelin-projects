package risk

import io.github.rajumark.kernelin.KernelinCpu
import io.github.rajumark.kernelin.kernelSource
import kotlinx.coroutines.runBlocking

/** Runs [pricePaths] on the CPU, either on one core or on all of them. */
class CpuEngine(private val parallel: Boolean) : PathEngine {
    override suspend fun run(market: Market, threads: Int, seed: Int): FloatArray {
        val out = FloatArray(threads * OUTPUTS_PER_THREAD)
        val m = market
        val kernel = {
            pricePaths(
                out, m.spot.toFloat(), m.strike.toFloat(), m.rate.toFloat(), m.vol.toFloat(),
                m.maturity.toFloat(), m.barrier.toFloat(), m.steps, PATHS_PER_THREAD, seed, 0,
            )
        }
        if (parallel) KernelinCpu.dispatchParallel(threads, kernel) else KernelinCpu.dispatch(threads, kernel)
        return out
    }
}

/**
 * Command line risk report on the JVM: `gradle jvmRun --args="1048576"` (number of paths, default 262144).
 * Prints every price next to its closed-form reference, so you can see the engine is right before trusting the GPU.
 */
fun main(args: Array<String>) = runBlocking {
    val paths = args.firstOrNull()?.toInt() ?: 262_144
    val market = Market()
    val cores = Runtime.getRuntime().availableProcessors()
    println("Monte Carlo options book: $paths paths x ${market.steps} days, ${PRODUCT_NAMES.size} products, 4 scenarios (base, spot ±1%, vol +1pt)")
    println("JVM ${System.getProperty("java.version")}, $cores cores\n")

    val report = riskReport(CpuEngine(parallel = true), market, paths, seed = 2026, name = "JVM, $cores cores") { System.nanoTime() / 1e6 }
    println("%-32s %10s %9s %10s %9s %8s %8s".format("product", "price", "± 95%", "exact", "delta", "gamma", "vega"))
    PRODUCT_NAMES.forEachIndexed { j, name ->
        val e = report.base.products[j]
        val exact = when (j) {
            0 -> Analytic.call(market)
            1 -> Analytic.put(market)
            2 -> Analytic.geometricAsianCall(market)
            else -> null
        }
        println(
            "%-32s %10.4f %9.4f %10s %9.4f %8.4f %8.4f".format(
                name, e.price, 1.96 * e.stdError, exact?.let { "%.4f".format(it) } ?: "-",
                report.delta[j], report.gamma[j], report.vega[j],
            ),
        )
    }
    val cv = report.base.arithmeticWithControl
    println("%-32s %10.4f %9.4f   (%.0fx less noise with the geometric Asian as control variate)".format(
        "Asian call (arithmetic, CV)", cv.price, 1.96 * cv.stdError,
        (report.base.products[3].stdError / cv.stdError).let { it * it },
    ))
    println("\nExact European call greeks: delta %.4f, gamma %.4f, vega %.4f".format(
        Analytic.callDelta(market), Analytic.callGamma(market), Analytic.callVega(market),
    ))
    println("Time: %.0f ms for 4 x %d paths".format(report.millis, paths))
    println("GPU shader generated by Kernelin: ${kernelSource(::pricePaths).wgsl.lines().size} lines of WGSL")
}
